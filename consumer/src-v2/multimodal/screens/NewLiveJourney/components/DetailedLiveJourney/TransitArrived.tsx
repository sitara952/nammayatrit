import { MultimodalTravelMode_multimodalTravelMode } from '@/readOnly/api/types/Enums.gen';
import { useHaptic } from '@/src-v2/utils/useHaptic';
import { useEffect } from 'react';
import { HapticFeedbackTypes } from 'react-native-haptic-feedback';
import Animated, {
    runOnJS,
    useAnimatedReaction,
    useAnimatedStyle,
    useSharedValue,
    withRepeat,
    withSequence,
    withTiming,
} from 'react-native-reanimated';
import Svg, { Path } from 'react-native-svg';

const WIGGLE_DEGREES = 2;
const WIGGLE_DURATION_MS = 100;

export const TransitArrived = ({ mode }: { mode: MultimodalTravelMode_multimodalTravelMode }) => {
    const rotation = useSharedValue(-WIGGLE_DEGREES);
    const hapticStartTime = useSharedValue(0);
    const haptic = useHaptic(HapticFeedbackTypes.selection, {
        enableVibrateFallback: true,
        ignoreAndroidSystemSettings: false,
    });
    useEffect(() => {
        rotation.value = withRepeat(
            withSequence(
                withTiming(WIGGLE_DEGREES, { duration: WIGGLE_DURATION_MS }),
                withTiming(-WIGGLE_DEGREES, { duration: WIGGLE_DURATION_MS }),
            ),
            -1,
            true,
        );
    }, []);

    const wiggleStyle = useAnimatedStyle(() => ({
        transform: [{ rotate: `${rotation.value}deg` }],
    }));

    useAnimatedReaction(
        () => rotation.value,
        (next, prev) => {
            if (!haptic) {
                return;
            }

            if (next !== prev && (next === WIGGLE_DEGREES || next === -WIGGLE_DEGREES)) {
                const now = Date.now();

                if (hapticStartTime.value === 0) {
                    hapticStartTime.value = now;
                }

                if (now - hapticStartTime.value <= 1000) {
                    runOnJS(haptic)();
                }
            }
        },
    );

    switch (mode) {
        case 'Bus':
            return (
                <Animated.View style={wiggleStyle}>
                    <BusArrived />
                </Animated.View>
            );
        case 'Metro':
            return (
                <Animated.View style={wiggleStyle}>
                    <MetroArrived />
                </Animated.View>
            );
        case 'Subway':
            return (
                <Animated.View style={wiggleStyle}>
                    <TrainArrived />
                </Animated.View>
            );
        default:
            return null;
    }
};

